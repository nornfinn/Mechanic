"""screenshot.queue / screenshot.results: capture the in-game UI after a reload.

screenshot.queue writes ``MECHANIC_SCREENSHOT_QUEUE`` to ``MechanicQueue.lua``
(replacing any queued Lua or API tests, like the other queue commands). After
the next /reload, !Mechanic waits for PLAYER_ENTERING_WORLD and, for each shot,
runs its ``setup`` code, waits ``delay`` seconds, calls ``Screenshot()`` and runs
``teardown``. The images land in ``<client>/Screenshots`` straight away; the
per-shot status reaches the desktop after a further /reload.
"""

import asyncio
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Dict, List, Optional

from afd import CommandResult, error, success
from afd.core.metadata import create_source
from pydantic import BaseModel, Field

from ..lua_strings import quote_lua_string
from ..targets import (
    DiagnosticTarget,
    SelectedTarget,
    TargetError,
    queue_target_lua,
    read_profile,
    select_target,
)
from .lua import escape_lua_string

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".tga"}
MATCH_BEFORE = timedelta(seconds=2)
MATCH_AFTER = timedelta(seconds=6)


class Shot(BaseModel):
    label: str = Field(
        ..., min_length=1, max_length=80, description="Name for the shot"
    )
    setup: Optional[str] = Field(
        None,
        description="Lua run before the shot, e.g. ToggleCharacter('PaperDollFrame')",
    )
    teardown: Optional[str] = Field(
        None, description="Lua run after the shot, e.g. HideUIPanel(CharacterFrame)"
    )
    delay: float = Field(
        1.0, ge=0, le=30, description="Seconds between setup and the shot"
    )


class ScreenshotQueueInput(BaseModel):
    target: Optional[DiagnosticTarget] = None
    shots: List[Shot] = Field(..., min_length=1, max_length=20)


class ScreenshotQueueResult(BaseModel):
    target: Optional[SelectedTarget] = None
    queued: List[str]
    queue_file: str
    message: str


class ScreenshotResultsInput(BaseModel):
    target: Optional[DiagnosticTarget] = None
    recent: int = Field(
        5, ge=0, le=50, description="Also list this many newest screenshot files"
    )


class ScreenshotResultsResult(BaseModel):
    target: Optional[SelectedTarget] = None
    screenshots_dir: str
    requested_at: Optional[str] = None
    last_run: Optional[str] = None
    results: List[Dict[str, Any]] = Field(
        default_factory=list, description="Per-shot status with the matched image file"
    )
    recent_files: List[Dict[str, Any]] = Field(
        default_factory=list, description="Newest image files in the Screenshots folder"
    )


def render_queue(shots: List[Shot], selected: Optional[SelectedTarget]) -> str:
    items = []
    for shot in shots:
        fields = [f'\t\t["label"] = {quote_lua_string(shot.label)},']
        if shot.setup:
            fields.append(f'\t\t["setup"] = {escape_lua_string(shot.setup)},')
        if shot.teardown:
            fields.append(f'\t\t["teardown"] = {escape_lua_string(shot.teardown)},')
        fields.append(f'\t\t["delay"] = {shot.delay!r},')
        items.append("\t{\n" + "\n".join(fields) + "\n\t}")
    content = (
        "-- Auto-generated by Mechanic Desktop CLI (screenshot.queue)\n"
        "-- This file is read by Mechanic on addon load\n"
        "-- Do not edit manually\n\n"
        "MECHANIC_SCREENSHOT_QUEUE = {\n" + ",\n".join(items) + "\n}\n"
    )
    if selected:
        content = queue_target_lua(selected) + content
    return content


def screenshot_files(directory: Path) -> List[Dict[str, Any]]:
    """Image files in the Screenshots folder, newest first."""
    if not directory.is_dir():
        return []
    files = []
    for path in directory.iterdir():
        if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES:
            modified = datetime.fromtimestamp(path.stat().st_mtime)
            files.append({"path": str(path), "modified": modified})
    files.sort(key=lambda f: f["modified"], reverse=True)
    return files


def match_file(taken_at: Any, files: List[Dict[str, Any]]) -> Optional[str]:
    """The file written closest to a shot's in-game timestamp, if any."""
    try:
        moment = datetime.strptime(str(taken_at), "%Y-%m-%d %H:%M:%S")
    except ValueError:
        return None
    nearby = [
        f
        for f in files
        if moment - MATCH_BEFORE <= f["modified"] <= moment + MATCH_AFTER
    ]
    if not nearby:
        return None
    return min(nearby, key=lambda f: abs(f["modified"] - moment))["path"]


def build_results(input: ScreenshotResultsInput) -> ScreenshotResultsResult:
    selected = select_target(input.target)
    directory = Path(selected.client or "") / "Screenshots"
    files = screenshot_files(directory)
    data = read_profile(selected).get("screenshotResults") or {}
    if not isinstance(data, dict):
        data = {}
    raw = data.get("results") or []
    if isinstance(raw, dict):
        raw = list(raw.values())
    results = []
    for item in raw:
        if not isinstance(item, dict):
            continue
        entry = dict(item)
        if entry.get("status") == "taken":
            entry["file"] = match_file(entry.get("takenAt"), files)
        results.append(entry)
    return ScreenshotResultsResult(
        target=selected,
        screenshots_dir=str(directory),
        requested_at=data.get("requestedAt"),
        last_run=data.get("lastRun"),
        results=results,
        recent_files=[
            {"path": f["path"], "modified": f["modified"].isoformat(timespec="seconds")}
            for f in files[: input.recent]
        ],
    )


def register_commands(server):
    @server.command(
        name="screenshot.queue",
        description=(
            "Queue in-game screenshots for the next /reload: each shot runs optional "
            "setup Lua, waits, calls Screenshot() and runs teardown. Replaces queued "
            "Lua/API tests"
        ),
        input_schema=ScreenshotQueueInput,
        output_schema=ScreenshotQueueResult,
    )
    async def screenshot_queue(
        input: ScreenshotQueueInput, context: Any = None
    ) -> CommandResult[ScreenshotQueueResult]:
        try:
            selected = await asyncio.to_thread(select_target, input.target)
        except TargetError as exc:
            return exc.result()
        queue_file = Path(selected.addon_path) / "MechanicQueue.lua"
        if not queue_file.parent.is_dir():
            return error(
                code="ADDON_NOT_FOUND",
                message=f"!Mechanic is not installed at {queue_file.parent}",
                suggestion="Install !Mechanic in the selected client and try again",
            )
        content = render_queue(input.shots, selected)
        await asyncio.to_thread(queue_file.write_text, content, encoding="utf-8")
        labels = [shot.label for shot in input.shots]
        return success(
            data=ScreenshotQueueResult(
                target=selected,
                queued=labels,
                queue_file=str(queue_file),
                message=(
                    f"Queued {len(labels)} screenshot(s). /reload in WoW; shots start "
                    "about 2 seconds after loading. Read them with screenshot.results"
                ),
            ),
            reasoning=f"Queued screenshots: {', '.join(labels)}",
            sources=[
                create_source(
                    type="file", id="mechanic-queue", title="MechanicQueue.lua"
                )
            ],
        )

    @server.command(
        name="screenshot.results",
        description=(
            "Per-shot results of the last screenshot.queue run (after a /reload) "
            "matched to image files, plus the newest files in the client's Screenshots folder"
        ),
        input_schema=ScreenshotResultsInput,
        output_schema=ScreenshotResultsResult,
    )
    async def screenshot_results(
        input: ScreenshotResultsInput, context: Any = None
    ) -> CommandResult[ScreenshotResultsResult]:
        try:
            result = await asyncio.to_thread(build_results, input)
        except TargetError as exc:
            return exc.result()
        taken = sum(1 for r in result.results if r.get("status") == "taken")
        if result.results:
            reasoning = f"{taken} of {len(result.results)} queued shots taken"
        else:
            reasoning = (
                "No saved screenshot results yet (they arrive after the next /reload)"
            )
        if result.recent_files:
            reasoning += f"; newest file {Path(result.recent_files[0]['path']).name}"
        return success(
            data=result,
            reasoning=reasoning,
            sources=[
                create_source(
                    type="file",
                    id="screenshots",
                    title="Screenshots folder",
                    location=result.screenshots_dir,
                )
            ],
        )
